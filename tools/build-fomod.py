#!/usr/bin/env python3
r"""Assemble the FOMOD package of Truly Nordic Carved Weapons Replacer from the staged build (assemble.py, textures.py).

LAYOUT
    Common                     every item but the mace: meshes, textures, the SkyPatcher weapon ini
    10 Mace - six-flanged      mace v3 (default): its meshes, textures and its own SkyPatcher ini
    11 Mace - classic          mace v2 (option): the same ini file name, pointing at the v2 model
    fomod\, README.md, NOTICE.md, CHANGELOG.md, LICENSE

HOW THE MODELS REPLACE VANILLA
    The weapons' WEAP model is set by SkyPatcher (filterByFirstPersonModelOr = the vanilla first-person STAT, so every
    copy of a weapon that shows that STAT is matched, whichever plugin made it). First-person models and the shield are
    loose files at the vanilla paths. The test hand-off and README say to put this mod below other Nordic replacers.

WHAT IT REFUSES
    * a staged file missing for any item;
    * a texture path in a shipped NIF that the package (core + the chosen option) does not contain;
    * a ModuleConfig.xml folder that came out missing or empty.
NEVER DELETES A PACKAGE: a package folder this build replaces is moved to <project>\_work\superseded-packages\<date>\.

Usage:  python tools/build-fomod.py [output folder]
"""
import os, re, sys, shutil, struct, time
import xml.etree.ElementTree as ET
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from items import ITEMS, WORK, MESH_REL, TEX_REL
STAGE = os.path.join(WORK, "stage")
NAME = "Truly Nordic Carved Weapons Replacer"
INI_DIR = r"SKSE\Plugins\SkyPatcher\weapon\TrulyNordicCarvedWeaponsReplacer"
CORE = ["sword", "battleaxe", "greatsword", "warhammer", "waraxe", "dagger", "bow", "shield"]
OPTIONS = {"10 Mace - six-flanged": "mace", "11 Mace - classic": "mace2"}

def fail(msg): print("FAILED: " + msg); sys.exit(1)
def version():
    t = open(os.path.join(REPO, "fomod", "info.xml"), encoding="utf-8").read()
    m = re.search(r"<Version>(\d+\.\d+\.\d+)</Version>", t)
    if not m: fail("no <Version>x.y.z</Version> in fomod/info.xml")
    return m.group(1)
def supersede(folder):
    p = os.path.dirname(os.path.abspath(folder)); root = None
    while not root:
        if os.path.isdir(os.path.join(p, "_work")): root = os.path.join(p, "_work", "superseded-packages")
        elif os.path.dirname(p) == p: root = os.path.join(os.path.dirname(os.path.abspath(folder)), "_superseded")
        else: p = os.path.dirname(p)
    day = os.path.join(root, time.strftime("%Y-%m-%d")); os.makedirs(day, exist_ok=True)
    to = os.path.join(day, "%s (replaced %s)" % (os.path.basename(os.path.normpath(folder)), time.strftime("%H%M%S")))
    shutil.move(folder, to); print("  previous package moved to", to)

def copytree(src, dst):
    for dp, _, fs in os.walk(src):
        for f in fs:
            s = os.path.join(dp, f); d = os.path.join(dst, os.path.relpath(s, src)); os.makedirs(os.path.dirname(d), exist_ok=True); shutil.copy2(s, d)

def ini_line(item):
    it = ITEMS[item]
    return f"filterByFirstPersonModelOr=Dragonborn.esm|{it['fp_stat'].lstrip('0')}:model={MESH_REL[len('meshes') + 1:]}\\{it['stem']}\\{it['stem']}.nif"

def place_item(item, dest):
    it = ITEMS[item]; src = os.path.join(STAGE, item)
    if not os.path.isdir(os.path.join(src, "meshes")): fail(f"no staged meshes for {item} ({src})")
    copytree(os.path.join(src, "meshes"), os.path.join(dest, "meshes"))
    t = os.path.join(STAGE, TEX_REL, it["stem"])
    if not os.path.isdir(t) or not os.listdir(t): fail(f"no staged textures for {item} ({t})")
    copytree(t, os.path.join(dest, TEX_REL, it["stem"]))

def nif_texture_paths(path):
    sys.path.insert(0, r"D:\Claude output\4. plans\nordic-double-bit-axe"); import niflib
    n = niflib.Nif(path); out = set()
    for b, t in enumerate(n.btypes):
        if t != "BSShaderTextureSet": continue
        tb = n.blocks[b]; k = struct.unpack_from("<I", tb, 0)[0]; q = 4
        for _ in range(k):
            L = struct.unpack_from("<I", tb, q)[0]; p = tb[q + 4:q + 4 + L].decode("latin-1"); q += 4 + L
            if p.lower().startswith("textures\\pbr\\apocryphatest"): out.add(p)
    return out

def write_ini(dest, lines, comment):
    p = os.path.join(dest, INI_DIR); os.makedirs(p, exist_ok=True)
    body = [f"; {NAME}: {comment}", "; Matched by the weapon's vanilla first-person model (the Dragonborn.esm STAT), so every enchanted",
            "; or added copy of the weapon that shows that model takes the new one. Generated by tools\\build-fomod.py."] + lines
    return body

def main(out_root=None):
    ver = version()
    if out_root is None:
        out_root = os.path.normpath(os.path.join(REPO, "..", "..", "7. current test builds", "Skyrim - " + NAME, f"{NAME} {ver}"))
    if os.path.isdir(out_root): supersede(out_root)
    os.makedirs(out_root)
    core = os.path.join(out_root, "Common")
    for item in CORE: place_item(item, core)
    lines = [ini_line(i) for i in CORE if i != "shield"]
    p = os.path.join(core, INI_DIR); os.makedirs(p, exist_ok=True)
    open(os.path.join(p, "TrulyNordicCarvedWeapons.ini"), "w", newline="\r\n").write("\n".join(write_ini(core, lines, "the new models, by weapon record")) + "\n")
    for folder, item in OPTIONS.items():
        d = os.path.join(out_root, folder); place_item(item, d); os.makedirs(os.path.join(d, INI_DIR), exist_ok=True)
        open(os.path.join(d, INI_DIR, "TrulyNordicCarvedWeapons_Mace.ini"), "w", newline="\r\n").write(
            "\n".join(write_ini(d, [ini_line(item)], f"the mace ({ITEMS[item]['version']})")) + "\n")
    fomod = os.path.join(out_root, "fomod"); os.makedirs(fomod)
    for f in ("info.xml", "ModuleConfig.xml"): shutil.copy2(os.path.join(REPO, "fomod", f), fomod)
    for f in ("README.md", "NOTICE.md", "CHANGELOG.md", "LICENSE"): shutil.copy2(os.path.join(REPO, f), out_root)
    # every folder the installer names exists and holds files
    root = ET.parse(os.path.join(fomod, "ModuleConfig.xml")).getroot()
    for s in sorted({e.get("source") for e in root.iter("folder")}):
        p = os.path.join(out_root, s)
        if not os.path.isdir(p) or not any(fs for _, _, fs in os.walk(p)): fail(f"ModuleConfig.xml installs from '{s}', but the package has nothing there")
    # every texture a shipped NIF names is in core or in the same option
    for folder in ["Common"] + list(OPTIONS):
        roots = [core] if folder == "Common" else [core, os.path.join(out_root, folder)]
        for dp, _, fs in os.walk(os.path.join(out_root, folder)):
            for f in fs:
                if not f.lower().endswith(".nif"): continue
                for t in nif_texture_paths(os.path.join(dp, f)):
                    if not any(os.path.isfile(os.path.join(r, t)) for r in roots): fail(f"{os.path.join(dp, f)} names {t}, which this install does not ship")
    total = sum(len(fs) for _, _, fs in os.walk(out_root))
    print(f"built {out_root}\n  version {ver}\n  core items {', '.join(CORE)}\n  mace options {', '.join(OPTIONS)}\n  files {total}")
    return out_root

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
